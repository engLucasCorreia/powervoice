#!/usr/bin/env node
// Generates docs/shortcuts.md — the full keyboard shortcut map, grouped by scope — from the
// shortcut registry (T-701 shortcut audit; T-705 wrote the original version of this script).
//
// The bindings and their scopes come from `ui/src/lib/shortcuts/registry.ts`'s `SHORTCUTS` —
// imported directly (Node 22+ can run erasable TypeScript natively, no build step / new
// dependency) so this can never drift from what the app actually does. `registry.ts` itself has
// only `import type` specifiers (erased at runtime, so nothing to resolve), which is exactly what
// makes it importable this way — don't add a runtime import to it without checking this script
// still works. Only the *display formatting* (which physical-key label and modifier order to
// print) is a small mirror of `ui/src/lib/shortcuts/shortcutLabel.ts`'s
// `formatBinding`/`keyLabel` — that file's own relative imports (`./actions`, `./registry`) have
// no extension, which the TS-in-Node loader can't resolve at runtime, so it can't be imported
// directly here; the formatting rules it implements are simple and stable enough to mirror
// instead. Labels come from `ui/src/lib/i18n/en.json`, read as plain JSON (not `import ... from
// "*.json"`, which needs an import attribute under plain Node ESM that the bundler-only rest of
// the app doesn't use) so a label can never drift from what the app actually shows either.
//
// Usage: node scripts/docs/generate_shortcuts.mjs [--check]
//   (no flag) rewrites docs/shortcuts.md
//   --check    exits 1 if the committed file would change (wired into `just check`)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const REGISTRY_URL = new URL("../../ui/src/lib/shortcuts/registry.ts", import.meta.url);
const MESSAGES_PATH = fileURLToPath(new URL("../../ui/src/lib/i18n/en.json", import.meta.url));
const OUT_PATH = fileURLToPath(new URL("../../docs/shortcuts.md", import.meta.url));

// Mirrors ui/src/lib/shortcuts/shortcutLabel.ts's CODE_LABELS.
const CODE_LABELS = {
  Space: "Space",
  Home: "Home",
  End: "End",
  Delete: "Delete",
  Escape: "Esc",
  Equal: "=",
  Minus: "-",
  ArrowUp: "↑",
  ArrowDown: "↓",
  ArrowLeft: "←",
  ArrowRight: "→",
};

// H-64 (SPEC-009 §2.4): a `key` binding (the produced character, e.g. "/") displays as itself;
// mirrors ui/src/lib/shortcuts/shortcutLabel.ts's keyLabel.
function keyLabel(binding) {
  if (binding.key !== undefined) return binding.key;
  const code = binding.code;
  if (CODE_LABELS[code]) return CODE_LABELS[code];
  const key = /^Key([A-Z])$/.exec(code);
  if (key) return key[1];
  const digit = /^Digit(\d)$/.exec(code);
  if (digit) return digit[1];
  return code;
}

// Mirrors ui/src/lib/shortcuts/shortcutLabel.ts's formatBinding.
function formatBinding(binding, isMac) {
  if (isMac) {
    let label = "";
    if (binding.shift) label += "⇧";
    if (binding.alt) label += "⌥";
    if (binding.mod) label += "⌘";
    return label + keyLabel(binding);
  }
  const parts = [];
  if (binding.mod) parts.push("Ctrl");
  if (binding.shift) parts.push("Shift");
  if (binding.alt) parts.push("Alt");
  parts.push(keyLabel(binding));
  return parts.join("+");
}

const SCOPE_HEADINGS = {
  global: "General",
  waveform: "Waveform view",
  dialog: "Dialogs",
  "text-input": "Text fields",
};
const SCOPE_ORDER = ["global", "waveform", "dialog", "text-input"];

async function loadShortcuts() {
  const mod = await import(REGISTRY_URL);
  return mod.SHORTCUTS;
}

function loadMessages() {
  return JSON.parse(readFileSync(MESSAGES_PATH, "utf8"));
}

function renderTable(rows) {
  const lines = rows.map((entry) => {
    const win = formatBinding(entry, false);
    const mac = formatBinding(entry, true);
    return `| ${entry.label} | \`${win}\` | \`${mac}\` |`;
  });
  return ["| Action | Windows / Linux | macOS |", "|---|---|---|", ...lines].join("\n");
}

function render(shortcuts, messages) {
  const byScope = new Map();
  for (const entry of shortcuts) {
    const label = messages[entry.labelKey];
    if (label === undefined) {
      throw new Error(`registry entry "${entry.action}" has labelKey "${entry.labelKey}", missing from en.json`);
    }
    const list = byScope.get(entry.scope) ?? [];
    list.push({ ...entry, label });
    byScope.set(entry.scope, list);
  }

  const sections = SCOPE_ORDER.filter((scope) => byScope.has(scope)).map(
    (scope) => `### ${SCOPE_HEADINGS[scope]}\n\n${renderTable(byScope.get(scope))}`,
  );

  const PROVISIONAL_ACTIONS = new Set(["record.toggle", "nr.capture_noise_print"]);
  const provisional = shortcuts
    .filter((entry) => PROVISIONAL_ACTIONS.has(entry.action))
    .map((entry) => messages[entry.labelKey]);

  return `<!-- Generated by \`scripts/docs/generate_shortcuts.mjs\` (\`just shortcuts-table\`) from
     \`ui/src/lib/shortcuts/registry.ts\` — the single source of truth the app itself uses, so
     this can't drift from what's actually bound. Do not hand-edit; \`just check\` fails if this
     file is stale. -->

# Keyboard shortcuts

Shortcuts aren't remappable in this version (PROMPT §2, locked). On macOS, Ctrl/⌘ in the app's own
menus becomes ⌘ — every table below shows both.

${sections.join("\n\n")}

Marked "provisional" above (${provisional.join(", ")}): these match Audition's default per the best
sources found so far (see \`specs/SPEC-002-recording-monitoring.md\` and
\`specs/SPEC-014-noise-reduction.md\`), but the canonical Adobe reference page
(\`helpx.adobe.com/audition/desktop/keyboard-shortcuts/default-keyboard-shortcuts.html\`) still
returns HTTP 403 to automated fetch (\`docs/references.md\`), so neither has an independent,
authoritative confirmation.

"Dialogs" and "Text fields" have no entries today — every dialog's own Escape/Enter handling is
local to that dialog, not a registry binding, and no shortcut is defined to fire *inside* a text
field beyond the browser's native editing keys. The scopes exist in the registry (\`ShortcutScope\`)
for when one is needed; see \`ui/src/lib/shortcuts/registry.ts\`'s doc comment for the dispatch
rule that keeps them conflict-free with "General"/"Waveform view" when that happens.
`;
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");

  const shortcuts = await loadShortcuts();
  const messages = loadMessages();
  const next = render(shortcuts, messages);

  if (check) {
    let current;
    try {
      current = readFileSync(OUT_PATH, "utf8");
    } catch {
      console.error(`${OUT_PATH} does not exist — run \`just shortcuts-table\`.`);
      process.exit(1);
    }
    if (next !== current) {
      console.error("docs/shortcuts.md is stale — run `just shortcuts-table`.");
      process.exit(1);
    }
    console.log("docs/shortcuts.md is up to date.");
    return;
  }

  writeFileSync(OUT_PATH, next, "utf8");
  console.log(`wrote ${OUT_PATH} (${shortcuts.length} bindings).`);
}

await main();
