#!/usr/bin/env node
// Generates the shortcuts table in docs/user-guide.md from the keymap registry (T-705).
//
// The actual bindings come from `ui/src/lib/keymap/bindings.ts`'s `DEFAULT_KEYMAP` — imported
// directly (Node 22+ can run erasable TypeScript natively, no build step / new dependency) so
// this can never drift from what the app actually does. Only the *display formatting* (which
// physical-key label and modifier order to print) is a small mirror of
// `ui/src/lib/keymap/shortcutLabel.ts`'s `formatBinding`/`keyLabel` — that file's own relative
// imports (`./bindings`, `./registry`) have no extension, which the TS-in-Node loader can't
// resolve at runtime, so it can't be imported directly here; the formatting rules it implements
// are simple and stable enough to mirror instead. Human-readable action descriptions are
// hand-written below (`ACTION_LABELS`) since the keymap has no display-name field.
//
// Usage: node scripts/docs/generate_shortcuts.mjs [--check]
//   (no flag) rewrites the table between the markers in docs/user-guide.md
//   --check    exits 1 if the committed file would change

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const BINDINGS_URL = new URL(
  "../../ui/src/lib/keymap/bindings.ts",
  import.meta.url,
);
const USER_GUIDE = new URL("../../docs/user-guide.md", import.meta.url);

const START = "<!-- SHORTCUTS:START (generated by scripts/docs/generate_shortcuts.mjs) -->";
const END = "<!-- SHORTCUTS:END -->";

// Mirrors ui/src/lib/keymap/shortcutLabel.ts's CODE_LABELS.
const CODE_LABELS = {
  Space: "Space",
  Home: "Home",
  End: "End",
  Delete: "Delete",
  Escape: "Esc",
  Equal: "=",
  Minus: "-",
  ArrowUp: "↑",
  ArrowDown: "↓",
  ArrowLeft: "←",
  ArrowRight: "→",
};

function keyLabel(code) {
  if (CODE_LABELS[code]) return CODE_LABELS[code];
  const key = /^Key([A-Z])$/.exec(code);
  if (key) return key[1];
  const digit = /^Digit(\d)$/.exec(code);
  if (digit) return digit[1];
  return code;
}

// Mirrors ui/src/lib/keymap/shortcutLabel.ts's formatBinding.
function formatBinding(binding, isMac) {
  if (isMac) {
    let label = "";
    if (binding.shift) label += "⇧";
    if (binding.alt) label += "⌥";
    if (binding.mod) label += "⌘";
    return label + keyLabel(binding.code);
  }
  const parts = [];
  if (binding.mod) parts.push("Ctrl");
  if (binding.shift) parts.push("Shift");
  if (binding.alt) parts.push("Alt");
  parts.push(keyLabel(binding.code));
  return parts.join("+");
}

// Human-readable description per action id (ui/src/lib/keymap/actions.ts is the id list; it
// carries no display text of its own).
const ACTION_LABELS = {
  "transport.play_pause": "Play / pause",
  "transport.play_from_start": "Play from start",
  "transport.return_to_start": "Return to start",
  "record.toggle": "Record (start/stop) — provisional binding",
  "marker.add": "Add marker",
  "marker.delete_selected": "Delete selected marker(s)",
  "marker.next": "Go to next marker",
  "marker.prev": "Go to previous marker",
  "history.undo": "Undo",
  "history.redo": "Redo",
  "file.open": "Open",
  "file.save": "Save",
  "file.save_as": "Save As",
  "waveform.zoom_in": "Zoom in (waveform)",
  "waveform.zoom_out": "Zoom out (waveform)",
  "edit.cut": "Cut",
  "edit.copy": "Copy",
  "edit.paste": "Paste",
  "edit.delete": "Delete selection",
  "edit.trim": "Trim to selection (Crop)",
  "waveform.select_all": "Select all",
  "waveform.deselect": "Clear selection",
  "nr.capture_noise_print": "Capture Noise Print — provisional binding",
  "spectral.toggle": "Show/hide the spectral pane",
};

async function loadKeymap() {
  const mod = await import(BINDINGS_URL);
  return mod.DEFAULT_KEYMAP;
}

function renderTable(keymap) {
  const rows = keymap.map((binding) => {
    const label = ACTION_LABELS[binding.action] ?? binding.action;
    const win = formatBinding(binding, false);
    const mac = formatBinding(binding, true);
    return `| ${label} | \`${win}\` | \`${mac}\` |`;
  });
  return [
    "| Action | Windows / Linux | macOS |",
    "|---|---|---|",
    ...rows,
  ].join("\n");
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");

  const keymap = await loadKeymap();
  const table = renderTable(keymap);
  const block = `${START}\n${table}\n${END}`;

  const guidePath = fileURLToPath(USER_GUIDE);
  const current = readFileSync(guidePath, "utf8");
  const pattern = new RegExp(
    `${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`,
  );

  if (!pattern.test(current)) {
    console.error(
      `docs/user-guide.md is missing the ${START} / ${END} markers — add them where the shortcuts table belongs.`,
    );
    process.exit(1);
  }

  const next = current.replace(pattern, block);

  if (check) {
    if (next !== current) {
      console.error("docs/user-guide.md's shortcuts table is stale — run `just shortcuts-table`.");
      process.exit(1);
    }
    console.log("docs/user-guide.md's shortcuts table is up to date.");
    return;
  }

  writeFileSync(guidePath, next, "utf8");
  console.log(`updated the shortcuts table in ${guidePath} (${keymap.length} bindings).`);
}

await main();
